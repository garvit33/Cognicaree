-- CareStream Database Schema (Supabase)

-- 1. Create a table for patients
CREATE TABLE patients (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  full_name TEXT NOT NULL,
  phone_number TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Create a table for inquiries (the raw voice/text input from the patient)
CREATE TABLE inquiries (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  patient_id UUID NOT NULL REFERENCES patients(id) ON DELETE CASCADE,
  raw_text TEXT NOT NULL,          -- Either the original text or transcribed audio
  has_audio BOOLEAN DEFAULT FALSE, -- Flag if there was an audio file attached
  status TEXT DEFAULT 'pending',   -- Values: pending, triaged, completed
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Create a table for triages (the AI generated output linking to the inquiry)
CREATE TABLE triages (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  inquiry_id UUID NOT NULL REFERENCES inquiries(id) ON DELETE CASCADE UNIQUE,
  urgency_level TEXT NOT NULL,     -- Values: High, Medium, Routine
  symptoms_json JSONB NOT NULL,    -- Extracted array of symptoms
  ai_draft_response TEXT NOT NULL, -- The response generated by GPT-4o
  doctor_approved BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Enable Row Level Security (RLS) - Basic setup for MVP
ALTER TABLE patients ENABLE ROW LEVEL SECURITY;
ALTER TABLE inquiries ENABLE ROW LEVEL SECURITY;
ALTER TABLE triages ENABLE ROW LEVEL SECURITY;

-- Create basic policies (Allowing anon inserts/reads for the hackathon MVP to avoid auth hurdles)
-- *Note: For a real production app, you would restrict this to authenticated users.*
CREATE POLICY "Allow public select" ON patients FOR SELECT USING (true);
CREATE POLICY "Allow public insert" ON patients FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow public select" ON inquiries FOR SELECT USING (true);
CREATE POLICY "Allow public insert" ON inquiries FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update" ON inquiries FOR UPDATE USING (true);

CREATE POLICY "Allow public select" ON triages FOR SELECT USING (true);
CREATE POLICY "Allow public insert" ON triages FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update" ON triages FOR UPDATE USING (true);
